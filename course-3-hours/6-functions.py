# Напишите функцию, которая принимает любое кол-во числовых аргументов 
# и возвращает их произведение

def multi( sample:str, num:int = 2):
	print(sample*num)

multi('ab')	

def multi_all(*args):
	result = 1
	for i in args:
		result *= i

	print(result)

multi_all( 2,2,3)	